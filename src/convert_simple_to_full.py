"""CLI wrapper for AgMIP simple-to-full humidity post-processing."""
import argparse
try:
    from .simple2full import convert_simple_to_full
except ImportError:
    from simple2full import convert_simple_to_full


def main():
    p=argparse.ArgumentParser(description="Convert a basic AgMIP file to a full humidity-consistent file")
    p.add_argument("--baseline",required=True,help="Baseline full .AgMIP station file")
    p.add_argument("--simple",required=True,help="Basic scenario file generated by delta method")
    p.add_argument("--output",required=True,help="Output full .AgMIP path")
    p.add_argument("--header",default=None)
    a=p.parse_args()
    convert_simple_to_full(a.baseline,a.simple,a.output,a.header)

if __name__=="__main__":main()
